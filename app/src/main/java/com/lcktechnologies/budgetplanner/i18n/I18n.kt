    private fun mapFor(lang: String): Map<String, String> = when (lang) {
        "si" -> SI
        "ta" -> TA
        else -> EN
    }

    fun get(lang: String, key: String): String = mapFor(lang)[key] ?: EN[key] ?: key

    /** Replaces {0}, {1}, ... in the string with [args]. */
    fun fmt(lang: String, key: String, vararg args: Any): String {
        var s = get(lang, key)
        args.forEachIndexed { i, a -> s = s.replace("{$i}", a.toString()) }
        return s
    }
